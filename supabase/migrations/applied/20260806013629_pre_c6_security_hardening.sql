create or replace function private.audit_progress_photo_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  insert into public.progress_photo_events (
    progress_photo_id, patient_id, care_episode_id, actor_id,
    event_type, before_state, after_state
  ) values (
    new.id,
    new.patient_id,
    new.care_episode_id,
