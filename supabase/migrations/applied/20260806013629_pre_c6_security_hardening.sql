-- Pre-C6 stabilization: notifications and private progress/anthropometry photos.

-- ---------------------------------------------------------------------------
-- Notifications: the legacy helper returned uuid while notifications.id is
-- bigint, and exposed an arbitrary-recipient SECURITY DEFINER path to clients.
-- No frontend consumer uses the public wrapper; keep the primitive private and
-- service-role only.
-- ---------------------------------------------------------------------------

drop function if exists public.create_notification(uuid, text, text, text, text, jsonb);
drop function if exists private.create_notification(uuid, text, text, text, text, jsonb);

create function private.create_notification(
  p_user_id uuid,
  p_type text default 'info',
  p_title text default null,
  p_message text default null,
  p_link_url text default null,
  p_content jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_id bigint;
begin
  if not exists (select 1 from auth.users account where account.id = p_user_id) then
    return null;
  end if;

  insert into public.notifications (
    user_id, type, title, message, link_url, content, is_read
  ) values (
    p_user_id,
    coalesce(nullif(trim(p_type), ''), 'info'),
    p_title,
    p_message,
    p_link_url,
    jsonb_strip_nulls(
      coalesce(p_content, '{}'::jsonb) ||
      jsonb_build_object('title', p_title, 'message', p_message, 'link_url', p_link_url)
    ),
    false
  ) returning id into v_id;

  return v_id;
end;
$function$;

revoke all on function private.create_notification(uuid, text, text, text, text, jsonb)
  from public, anon, authenticated;
grant execute on function private.create_notification(uuid, text, text, text, text, jsonb)
  to service_role;

