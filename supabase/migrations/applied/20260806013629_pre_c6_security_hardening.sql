create or replace function private.audit_notification_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if tg_op = 'DELETE' then
    insert into public.notification_events(
      notification_id,user_id,actor_id,event_type,snapshot
    ) values (
      old.id,old.user_id,auth.uid(),'deleted',to_jsonb(old)
    );
    return old;
  end if;

  if new.is_read is distinct from old.is_read then
    insert into public.notification_events(
      notification_id,user_id,actor_id,event_type,snapshot
    ) values (
      new.id,new.user_id,auth.uid(),'read_state_changed',to_jsonb(new)
    );
  end if;
  return new;
end;
$function$;

revoke all on function private.audit_notification_change()
  from public, anon, authenticated;

drop trigger if exists trg_audit_notification_change on public.notifications;
create trigger trg_audit_notification_change
after update or delete on public.notifications
for each row execute function private.audit_notification_change();

-- ---------------------------------------------------------------------------
-- Progress photos: preserve clinical history, bind every object to the care
-- episode, replace public URLs with short-lived signed URLs in the client, and
-- invalidate instead of hard-deleting rows or Storage objects.
-- ---------------------------------------------------------------------------

alter table public.progress_photos
  add column if not exists storage_path text,
  add column if not exists status text not null default 'active',
  add column if not exists invalidated_at timestamptz,
  add column if not exists invalidated_by uuid references public.user_profiles(id) on delete set null,
  add column if not exists invalidation_reason text;

update public.progress_photos
set storage_path = case
  when photo_url like '%/storage/v1/object/public/patient-photos/%'
    then split_part(photo_url, '/storage/v1/object/public/patient-photos/', 2)
  when photo_url like '%/storage/v1/object/sign/patient-photos/%'
    then split_part(split_part(photo_url, '/storage/v1/object/sign/patient-photos/', 2), '?', 1)
  when photo_url like 'patient-photos/%'
    then substring(photo_url from length('patient-photos/') + 1)
  else photo_url
end
where storage_path is null or trim(storage_path) = '';

update public.progress_photos photo
set care_episode_id = (
  select candidate.id
  from public.care_episodes candidate
  where candidate.patient_id = photo.patient_id
  order by
    case
      when photo.photo_date >= candidate.started_at::date
       and (candidate.ended_at is null or photo.photo_date <= candidate.ended_at::date)
      then 0 else 1
    end,
    (candidate.status = 'active') desc,
    candidate.started_at desc
  limit 1
)
where photo.care_episode_id is null;

alter table public.progress_photos
  drop constraint if exists progress_photos_status_check;
alter table public.progress_photos
  add constraint progress_photos_status_check
  check (status in ('active', 'invalidated'));

alter table public.progress_photos
  drop constraint if exists progress_photos_invalidation_check;
alter table public.progress_photos
  add constraint progress_photos_invalidation_check
  check (
    (status = 'active' and invalidated_at is null and invalidated_by is null and invalidation_reason is null)
    or
    (status = 'invalidated' and invalidated_at is not null and invalidated_by is not null and length(trim(invalidation_reason)) >= 3)
  );

create unique index if not exists progress_photos_storage_path_uidx
  on public.progress_photos(storage_path)
  where storage_path is not null;
create index if not exists progress_photos_episode_status_idx
  on public.progress_photos(care_episode_id, status, photo_date desc);

