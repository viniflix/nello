create or replace function private.protect_progress_photo_identity()
returns trigger
language plpgsql
security definer
set search_path = ''
as $function$
begin
  if new.patient_id is distinct from old.patient_id
     or new.care_episode_id is distinct from old.care_episode_id
     or new.storage_path is distinct from old.storage_path
     or new.photo_url is distinct from old.photo_url
     or new.uploaded_by is distinct from old.uploaded_by then
    raise exception 'A identidade e o arquivo de uma foto clínica são imutáveis.' using errcode = '23514';
  end if;
  return new;
end;
$function$;

