-- Forward-only internal notice outbox. No clinical history or legacy flags rewritten.
BEGIN;
SET LOCAL ROLE postgres;
CREATE TABLE public.appointment_notifications (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 appointment_id bigint REFERENCES public.appointments(id) ON DELETE SET NULL,
 nutritionist_id uuid NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
 patient_id uuid REFERENCES public.user_profiles(id) ON DELETE CASCADE,
 care_episode_id uuid REFERENCES public.care_episodes(id) ON DELETE SET NULL,
 appointment_time timestamptz NOT NULL,
 event_kind text NOT NULL CHECK(event_kind IN ('reminder','post_consultation')),
 event_key text NOT NULL UNIQUE,
 channel text NOT NULL DEFAULT 'in_app',
 template_id bigint REFERENCES public.message_templates(id) ON DELETE SET NULL,
 scheduled_for timestamptz NOT NULL,
 delivery_status text NOT NULL CHECK(delivery_status IN ('queued','available','failed','cancelled','superseded','blocked','legacy_unverified')),
 reason_code text,
 attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 3),
 next_attempt_at timestamptz NOT NULL DEFAULT now(),
 last_error_code text,
 notification_id bigint REFERENCES public.notifications(id) ON DELETE SET NULL,
 available_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX appointment_notices_owner_history ON public.appointment_notifications(nutritionist_id,appointment_id,created_at DESC);
CREATE INDEX appointment_notices_appointment ON public.appointment_notifications(appointment_id,created_at DESC);
CREATE INDEX appointment_notices_patient ON public.appointment_notifications(patient_id);
CREATE INDEX appointment_notices_care ON public.appointment_notifications(care_episode_id,delivery_status);
CREATE INDEX appointment_notices_template ON public.appointment_notifications(template_id) WHERE template_id IS NOT NULL;
CREATE INDEX appointment_notices_due ON public.appointment_notifications(next_attempt_at,scheduled_for,id)
 WHERE delivery_status IN ('queued','failed') AND attempts<3;
ALTER TABLE public.appointment_notifications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.appointment_notifications FROM PUBLIC,anon,authenticated;
GRANT SELECT ON public.appointment_notifications TO authenticated;
GRANT ALL ON public.appointment_notifications TO service_role;
REVOKE ALL ON SEQUENCE public.appointment_notifications_id_seq FROM PUBLIC,anon,authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.appointment_notifications_id_seq TO service_role;
CREATE POLICY wave05_active_actor ON public.appointment_notifications AS RESTRICTIVE FOR ALL TO authenticated
 USING (private.wave05_active_actor()) WITH CHECK (private.wave05_active_actor());
CREATE POLICY appointment_notices_owner ON public.appointment_notifications FOR SELECT TO authenticated
 USING(nutritionist_id=auth.uid() AND private.wave09_professional_actor()
   AND (care_episode_id IS NULL OR private.can_read_care_episode(care_episode_id)));

CREATE FUNCTION private.agenda_notice_key(p_id bigint,p_time timestamptz,p_patient uuid)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path='' AS $f$
 SELECT 'reminder:'||p_id::text||':'||extract(epoch FROM p_time)::text||':'||coalesce(p_patient::text,'guest')
$f$;
REVOKE ALL ON FUNCTION private.agenda_notice_key(bigint,timestamptz,uuid) FROM PUBLIC,anon,authenticated;

CREATE FUNCTION private.enroll_agenda_notices(p_id bigint,p_post boolean DEFAULT false,p_preserve_legacy boolean DEFAULT true)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
DECLARE a public.appointments%ROWTYPE;t public.message_templates%ROWTYPE;v_key text;v_state text;v_reason text;
BEGIN
 SELECT * INTO a FROM public.appointments WHERE id=p_id;
 IF NOT FOUND THEN RETURN; END IF;
 v_key:=private.agenda_notice_key(a.id,a.appointment_time,a.patient_id);
 -- Retain history; an invalidated notice no longer presents an obsolete schedule.
 UPDATE public.notifications n SET type=CASE WHEN a.status='cancelled' THEN 'appointment_canceled' WHEN a.status IN ('completed','no_show') THEN 'appointment_notice_closed' ELSE 'appointment_rescheduled' END,
   title=CASE WHEN a.status IN ('cancelled','completed','no_show') THEN 'Lembrete encerrado' ELSE 'Consulta reagendada' END,
   message=CASE WHEN a.status IN ('cancelled','completed','no_show') THEN 'Este lembrete não corresponde a uma consulta futura. Confira o Nello.' ELSE 'O horário foi alterado. Confira o agendamento atual no Nello.' END,
   content=jsonb_build_object('appointment_id',a.id,'appointment_time',a.appointment_time),link_url='/patient'
 FROM public.appointment_notifications q WHERE q.appointment_id=a.id AND q.event_kind='reminder' AND q.notification_id=n.id
   AND q.delivery_status='available' AND (q.event_key<>v_key OR a.status NOT IN ('scheduled','awaiting_confirmation','confirmed'));
 UPDATE public.appointment_notifications SET delivery_status=CASE WHEN a.status IN ('cancelled','completed','no_show') THEN 'cancelled' ELSE 'superseded' END,
   reason_code='appointment_changed',updated_at=clock_timestamp()
 WHERE appointment_id=a.id AND event_kind='reminder' AND delivery_status IN ('queued','failed','available','blocked','legacy_unverified')
   AND (event_key<>v_key OR a.status NOT IN ('scheduled','awaiting_confirmation','confirmed'));
 IF a.status IN ('scheduled','awaiting_confirmation','confirmed') AND a.appointment_time>now() THEN
   v_state:='queued';v_reason:=NULL;
   IF a.patient_id IS NULL THEN v_state:='blocked';v_reason:='no_patient_account';
   ELSIF p_preserve_legacy AND a.reminder_sent_at IS NOT NULL THEN v_state:='legacy_unverified';v_reason:='legacy_notice_unverified'; END IF;
   INSERT INTO public.appointment_notifications(appointment_id,nutritionist_id,patient_id,care_episode_id,appointment_time,event_kind,event_key,scheduled_for,delivery_status,reason_code)
   VALUES(a.id,a.nutritionist_id,a.patient_id,a.care_episode_id,a.appointment_time,'reminder',v_key,a.appointment_time-interval '48 hours',v_state,v_reason)
   ON CONFLICT(event_key) DO NOTHING;
 END IF;
 IF p_post AND a.status='completed' AND a.patient_id IS NOT NULL THEN
   SELECT * INTO t FROM public.message_templates WHERE nutritionist_id=a.nutritionist_id AND context='post_consultation' AND is_active
     ORDER BY use_count DESC,id LIMIT 1;
   v_state:=CASE WHEN t.id IS NULL OR t.channel<>'in_app' THEN 'blocked' ELSE 'queued' END;
   v_reason:=CASE WHEN t.id IS NULL THEN 'no_active_template' WHEN t.channel<>'in_app' THEN 'external_channel_unconfigured' END;
   INSERT INTO public.appointment_notifications(appointment_id,nutritionist_id,patient_id,care_episode_id,appointment_time,event_kind,event_key,channel,template_id,scheduled_for,delivery_status,reason_code)
   VALUES(a.id,a.nutritionist_id,a.patient_id,a.care_episode_id,a.appointment_time,'post_consultation','post:'||a.id::text,coalesce(t.channel,'in_app'),t.id,now(),v_state,v_reason)
   ON CONFLICT(event_key) DO NOTHING;
 END IF;
END $f$;
REVOKE ALL ON FUNCTION private.enroll_agenda_notices(bigint,boolean,boolean) FROM PUBLIC,anon,authenticated;

CREATE FUNCTION private.track_agenda_notices() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
BEGIN
 IF TG_OP='DELETE' THEN
   UPDATE public.notifications n SET type='appointment_canceled',title='Consulta removida',message='Este agendamento foi removido. Confira o Nello.',link_url='/patient'
     FROM public.appointment_notifications q WHERE q.appointment_id=OLD.id AND q.notification_id=n.id AND q.delivery_status='available';
   UPDATE public.appointment_notifications SET delivery_status='cancelled',reason_code='appointment_deleted',updated_at=clock_timestamp() WHERE appointment_id=OLD.id;
   RETURN OLD;
 END IF;
 PERFORM private.enroll_agenda_notices(NEW.id,TG_OP='UPDATE' AND NEW.status='completed' AND OLD.status IS DISTINCT FROM NEW.status,
   TG_OP='UPDATE' AND OLD.appointment_time IS NOT DISTINCT FROM NEW.appointment_time AND OLD.patient_id IS NOT DISTINCT FROM NEW.patient_id);
 RETURN NEW;
END $f$;
REVOKE ALL ON FUNCTION private.track_agenda_notices() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER agenda_notice_enrollment AFTER INSERT OR UPDATE OF appointment_time,patient_id,status,care_episode_id ON public.appointments
 FOR EACH ROW EXECUTE FUNCTION private.track_agenda_notices();
CREATE TRIGGER agenda_notice_deletion BEFORE DELETE ON public.appointments FOR EACH ROW EXECUTE FUNCTION private.track_agenda_notices();

CREATE FUNCTION private.deliver_agenda_notice(p_id bigint) RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
DECLARE q public.appointment_notifications%ROWTYPE;a public.appointments%ROWTYPE;t public.message_templates%ROWTYPE;
 v_appointment bigint;v_notification bigint;v_name text;v_title text;v_body text;v_type text;v_reason text;v_episode uuid;v_patient uuid;
BEGIN
 SELECT appointment_id INTO v_appointment FROM public.appointment_notifications WHERE id=p_id;
 -- Same lock order as clinical writes: appointment, then notice. Never wait on a busy appointment.
 SELECT * INTO a FROM public.appointments WHERE id=v_appointment FOR UPDATE SKIP LOCKED;
 IF NOT FOUND THEN RETURN false; END IF;
 IF a.care_episode_id IS NOT NULL THEN
   SELECT id INTO v_episode FROM public.care_episodes WHERE id=a.care_episode_id FOR SHARE SKIP LOCKED;
   IF NOT FOUND THEN RETURN false; END IF;
 END IF;
 IF a.patient_id IS NOT NULL THEN
   SELECT id INTO v_patient FROM public.user_profiles WHERE id=a.patient_id FOR SHARE SKIP LOCKED;
   IF NOT FOUND THEN RETURN false; END IF;
 END IF;
 SELECT * INTO q FROM public.appointment_notifications WHERE id=p_id FOR UPDATE SKIP LOCKED;
 IF NOT FOUND OR q.delivery_status NOT IN ('queued','failed') OR q.attempts>=3 OR q.scheduled_for>now() OR q.next_attempt_at>now() THEN RETURN false; END IF;
 IF q.patient_id IS DISTINCT FROM a.patient_id OR q.care_episode_id IS DISTINCT FROM a.care_episode_id
   OR q.appointment_time IS DISTINCT FROM a.appointment_time THEN v_reason:='appointment_changed';
 ELSIF NOT EXISTS(SELECT 1 FROM auth.users account JOIN public.user_profiles p ON p.id=account.id WHERE account.id=a.patient_id AND p.is_active) THEN v_reason:='no_patient_account';
 ELSIF NOT private.has_current_clinical_capacity(a.nutritionist_id) THEN v_reason:='professional_inactive';
 ELSIF NOT EXISTS(SELECT 1 FROM public.care_episodes e WHERE e.id=a.care_episode_id AND e.status='active' AND e.patient_id=a.patient_id AND e.nutritionist_id=a.nutritionist_id) THEN v_reason:='care_inactive';
 ELSIF q.event_kind='reminder' AND (a.status NOT IN ('scheduled','awaiting_confirmation','confirmed') OR a.appointment_time<=now()) THEN v_reason:='appointment_not_upcoming';
 ELSIF q.event_kind='post_consultation' AND a.status<>'completed' THEN v_reason:='appointment_not_completed'; END IF;
 IF v_reason IS NOT NULL THEN UPDATE public.appointment_notifications SET delivery_status='cancelled',reason_code=v_reason,updated_at=clock_timestamp() WHERE id=q.id;RETURN false;END IF;
 IF q.channel<>'in_app' THEN UPDATE public.appointment_notifications SET delivery_status='blocked',reason_code='external_channel_unconfigured',updated_at=clock_timestamp() WHERE id=q.id;RETURN false;END IF;
 v_type:='appointment_reminder';v_title:='Lembrete de consulta';
 v_body:='Sua consulta está agendada para '||to_char(a.appointment_time AT TIME ZONE 'America/Fortaleza','DD/MM/YYYY "às" HH24:MI')||'. Confira o Nello para os detalhes.';
 IF q.event_kind='post_consultation' THEN
   SELECT * INTO t FROM public.message_templates WHERE id=q.template_id AND nutritionist_id=a.nutritionist_id AND is_active AND context='post_consultation' FOR UPDATE;
   IF NOT FOUND OR t.channel<>'in_app' THEN UPDATE public.appointment_notifications SET delivery_status='blocked',reason_code='template_unavailable',updated_at=clock_timestamp() WHERE id=q.id;RETURN false;END IF;
   SELECT name INTO v_name FROM public.user_profiles WHERE id=a.patient_id;
   v_title:=coalesce(t.title_template,'Pós-consulta');v_body:=coalesce(t.body_template,'');v_type:='post_consultation';
   v_title:=replace(replace(replace(replace(v_title,'{{nome_paciente}}',coalesce(v_name,'')),'{{data_hoje}}',to_char(now() AT TIME ZONE 'America/Fortaleza','DD/MM/YYYY')),'{{data_consulta}}',to_char(a.appointment_time AT TIME ZONE 'America/Fortaleza','DD/MM/YYYY')),'{{hora_consulta}}',to_char(a.appointment_time AT TIME ZONE 'America/Fortaleza','HH24:MI'));
   v_body:=replace(replace(replace(replace(v_body,'{{nome_paciente}}',coalesce(v_name,'')),'{{data_hoje}}',to_char(now() AT TIME ZONE 'America/Fortaleza','DD/MM/YYYY')),'{{data_consulta}}',to_char(a.appointment_time AT TIME ZONE 'America/Fortaleza','DD/MM/YYYY')),'{{hora_consulta}}',to_char(a.appointment_time AT TIME ZONE 'America/Fortaleza','HH24:MI'));
   IF length(v_title)>300 OR length(v_body)>8000 OR v_title~'\{\{[^}]+\}\}' OR v_body~'\{\{[^}]+\}\}' THEN
     UPDATE public.appointment_notifications SET delivery_status='blocked',reason_code='template_variables_or_size',updated_at=clock_timestamp() WHERE id=q.id;RETURN false;
   END IF;
 END IF;
 UPDATE public.appointment_notifications SET attempts=attempts+1,updated_at=clock_timestamp() WHERE id=q.id;
 BEGIN
   INSERT INTO public.notifications(user_id,type,title,message,link_url,content,is_read)
   VALUES(a.patient_id,v_type,v_title,v_body,'/patient',jsonb_build_object('appointment_id',a.id,'appointment_time',a.appointment_time),false) RETURNING id INTO v_notification;
   UPDATE public.appointment_notifications SET delivery_status='available',notification_id=v_notification,available_at=clock_timestamp(),last_error_code=NULL,reason_code=NULL,updated_at=clock_timestamp() WHERE id=q.id;
   IF t.id IS NOT NULL THEN
     INSERT INTO public.template_dispatch_log(template_id,nutritionist_id,patient_id,channel,trigger_event,rendered_title,rendered_body,variables_used,delivery_status,metadata)
       VALUES(t.id,a.nutritionist_id,a.patient_id,'in_app','appointment_completed',v_title,v_body,'{}'::jsonb,'sent',jsonb_build_object('appointment_id',a.id,'notification_id',v_notification,'delivery_evidence','internal_available'));
     UPDATE public.message_templates SET use_count=use_count+1,last_used_at=clock_timestamp() WHERE id=t.id;
   END IF;
   RETURN true;
 EXCEPTION WHEN OTHERS THEN
   UPDATE public.appointment_notifications SET delivery_status='failed',last_error_code=SQLSTATE,
     next_attempt_at=now()+make_interval(mins=>power(2,attempts-1)::integer),updated_at=clock_timestamp() WHERE id=q.id;
   RETURN false;
 END;
END $f$;
REVOKE ALL ON FUNCTION private.deliver_agenda_notice(bigint) FROM PUBLIC,anon,authenticated;

CREATE FUNCTION public.sync_appointment_notification_schedule(p_appointment_id bigint,p_force_reschedule boolean DEFAULT false)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
DECLARE a public.appointments%ROWTYPE;q record;v_events jsonb;
BEGIN
 IF auth.uid() IS NULL OR NOT private.has_current_clinical_capacity(auth.uid()) THEN RAISE EXCEPTION USING errcode='42501',message='forbidden';END IF;
 SELECT * INTO a FROM public.appointments WHERE id=p_appointment_id AND nutritionist_id=auth.uid() FOR UPDATE;
 IF NOT FOUND OR (a.care_episode_id IS NOT NULL AND NOT private.can_read_care_episode(a.care_episode_id)) THEN RAISE EXCEPTION USING errcode='42501',message='forbidden';END IF;
 -- Force reconciles the schedule; it never resets a completed attempt or legacy marker.
 PERFORM private.enroll_agenda_notices(a.id,false,true);
 FOR q IN SELECT id FROM public.appointment_notifications WHERE appointment_id=a.id AND delivery_status IN ('queued','failed') ORDER BY id LIMIT 10 LOOP
   PERFORM private.deliver_agenda_notice(q.id);
 END LOOP;
 SELECT coalesce(jsonb_agg(jsonb_build_object('event_kind',event_kind,'delivery_status',delivery_status,'reason_code',reason_code)),'[]'::jsonb)
 INTO v_events FROM public.appointment_notifications WHERE appointment_id=a.id AND delivery_status NOT IN ('cancelled','superseded');
 RETURN jsonb_build_object('events',v_events);
END $f$;
REVOKE ALL ON FUNCTION public.sync_appointment_notification_schedule(bigint,boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.sync_appointment_notification_schedule(bigint,boolean) TO authenticated;

CREATE FUNCTION public.process_appointment_notifications(p_limit integer DEFAULT 50)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
DECLARE q record;v_count integer:=0;
BEGIN
 IF coalesce(auth.role(),'')<>'service_role' AND session_user NOT IN ('postgres','supabase_admin') THEN RAISE EXCEPTION USING errcode='42501',message='forbidden';END IF;
 IF p_limit IS NULL OR p_limit<1 OR p_limit>200 THEN RAISE EXCEPTION USING errcode='22023',message='invalid_limit';END IF;
 FOR q IN SELECT id FROM public.appointment_notifications WHERE delivery_status IN ('queued','failed') AND attempts<3 AND scheduled_for<=now() AND next_attempt_at<=now() ORDER BY scheduled_for,id LIMIT p_limit LOOP
   IF private.deliver_agenda_notice(q.id) THEN v_count:=v_count+1;END IF;
 END LOOP;
 RETURN jsonb_build_object('available',v_count);
END $f$;
REVOKE ALL ON FUNCTION public.process_appointment_notifications(integer) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.process_appointment_notifications(integer) TO service_role;

CREATE OR REPLACE FUNCTION private.create_appointment_reminders() RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
DECLARE v_appointment record;
BEGIN
 PERFORM private.wave05_require_active_actor();
 FOR v_appointment IN SELECT appointment.id FROM public.appointments appointment
   JOIN auth.users account ON account.id=appointment.patient_id
   WHERE appointment.status IN ('scheduled','awaiting_confirmation','confirmed') AND appointment.appointment_time>now()
     AND NOT EXISTS(SELECT 1 FROM public.appointment_notifications q WHERE q.event_key=private.agenda_notice_key(appointment.id,appointment.appointment_time,appointment.patient_id))
   ORDER BY appointment.appointment_time,appointment.id LIMIT 200 FOR UPDATE OF appointment SKIP LOCKED
 LOOP PERFORM private.enroll_agenda_notices(v_appointment.id,false,true); END LOOP;
 PERFORM public.process_appointment_notifications(50);
END $f$;
REVOKE ALL ON FUNCTION private.create_appointment_reminders() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION private.create_appointment_reminders() TO postgres,service_role;

CREATE FUNCTION private.close_care_agenda_notices() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $f$
BEGIN
 IF NEW.status<>'active' AND OLD.status IS DISTINCT FROM NEW.status THEN
   UPDATE public.notifications n SET type='appointment_notice_closed',title='Lembrete encerrado',message='Este lembrete pertence a um acompanhamento encerrado. Confira o Nello.',link_url='/patient'
     FROM public.appointment_notifications q WHERE q.care_episode_id=NEW.id AND q.event_kind='reminder' AND q.delivery_status='available' AND q.notification_id=n.id;
   UPDATE public.appointment_notifications SET delivery_status='cancelled',reason_code='care_inactive',updated_at=clock_timestamp()
     WHERE care_episode_id=NEW.id AND (delivery_status IN ('queued','failed') OR (event_kind='reminder' AND delivery_status='available'));
 END IF;
 RETURN NEW;
END $f$;
REVOKE ALL ON FUNCTION private.close_care_agenda_notices() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER agenda_notice_care_end AFTER UPDATE OF status ON public.care_episodes FOR EACH ROW EXECUTE FUNCTION private.close_care_agenda_notices();
NOTIFY pgrst,'reload schema';
COMMIT;
